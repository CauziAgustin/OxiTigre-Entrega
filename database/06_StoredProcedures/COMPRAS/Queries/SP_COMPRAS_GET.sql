Parámetros de entrada: @I_ID_EMPRESA, @S_ID_SESION, @S_ID_USUARIO.
Parámetros de salida: @O_CODIGO_ERROR, @O_MENSAJE.
Retorno: Devuelve los conjuntos de filas definidos por sus SELECT finales.
Tablas utilizadas: COMPRAS.ORDENES_COMPRA - SELECT; COMPRAS.ORDENES_COMPRA_DETALLES - SELECT; COMPRAS.PROVEEDORES - SELECT; COMPRAS.PROVEEDORES_CONTACTOS - SELECT; COMPRAS.RECEPCIONES_COMPRA - SELECT; COMPRAS.RECEPCIONES_COMPRA_DETALLES - SELECT; CONFIGURACION.UNIDADES_MEDIDA - SELECT; INVENTARIO.DEPOSITOS - SELECT; INVENTARIO.PRODUCTOS - SELECT.
