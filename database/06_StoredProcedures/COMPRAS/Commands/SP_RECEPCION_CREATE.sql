Descripción funcional: Confirma una recepción parcial; solo lo aceptado ingresa al stock.
Contrato de entrada:
- @I_ID_ORDEN_COMPRA y @I_ROW_VERSION identifican una orden APROBADA o RECIBIDA_PARCIAL sin cambios concurrentes.
- @I_DETALLES_JSON contiene PurchaseOrderLineId, AcceptedQuantity, RejectedQuantity y DamagedQuantity por renglón; la BLL exige DifferenceReason si hay rechazo o daño.
- Lots, SerialNumbers y ContainerContents describen únicamente el material aceptado; las cantidades trazadas deben coincidir con las aceptadas según el tipo de producto.
- @I_NUMERO_REMITO es opcional, pero no puede repetirse dentro de la empresa cuando se informa.
Efecto confirmado: crea el movimiento de entrada solo para cantidades aceptadas; guarda recepción, diferencias, lotes, activos y mediciones; deja pendiente el saldo no aceptado y audita el cambio de estado.
Errores funcionales: 50003 orden o versión no operable; 50005 exceso sobre saldo; 50006 remito duplicado; 50007 trazabilidad inconsistente. Las validaciones generales y errores SQL se propagan con THROW.
Parámetros de entrada: @I_DETALLES_JSON, @I_FECHA_RECEPCION_UTC, @I_ID_EMPRESA, @I_ID_ORDEN_COMPRA, @I_NUMERO_REMITO, @I_OBSERVACION, @I_ROW_VERSION, @S_ID_SESION, @S_ID_USUARIO.
Parámetros de salida: @O_CODIGO_ERROR, @O_FILAS_AFECTADAS, @O_ID_RECEPCION, @O_MENSAJE.
Retorno: Informa el resultado mediante los parámetros de salida declarados.
Tablas utilizadas: AUDITORIA.BITACORA_CAMBIOS_ESTADO - INSERT; COMPRAS.ORDENES_COMPRA - SELECT/UPDATE; COMPRAS.ORDENES_COMPRA_DETALLES - SELECT; COMPRAS.RECEPCIONES_COMPRA - INSERT/SELECT; COMPRAS.RECEPCIONES_COMPRA_DETALLES - INSERT/SELECT; CONFIGURACION.UNIDADES_MEDIDA - SELECT; INVENTARIO.ACTIVOS - INSERT/SELECT; INVENTARIO.ACTIVOS_CONTENIDOS - INSERT; INVENTARIO.ACTIVOS_EVENTOS - INSERT; INVENTARIO.LOTES - INSERT/SELECT; INVENTARIO.LOTES_EXISTENCIAS - INSERT; INVENTARIO.MEDICIONES_ACTIVOS - INSERT; INVENTARIO.MOVIMIENTOS_DETALLES - SELECT; INVENTARIO.MOVIMIENTOS_DETALLES_ACTIVOS - INSERT; INVENTARIO.MOVIMIENTOS_DETALLES_LOTES - INSERT; INVENTARIO.PRODUCTOS - SELECT.
Transacción: Abre una transacción explícita para agrupar sus escrituras.
