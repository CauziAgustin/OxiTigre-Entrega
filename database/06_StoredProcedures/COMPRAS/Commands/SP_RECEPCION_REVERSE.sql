Descripción funcional: Compensa una recepción intacta sin eliminar el documento ni su trazabilidad.
Retorno: Informa el resultado mediante los parámetros de salida declarados.
Tablas utilizadas: AUDITORIA.BITACORA_CAMBIOS_ESTADO - INSERT; COMPRAS.ORDENES_COMPRA - SELECT/UPDATE; COMPRAS.ORDENES_COMPRA_DETALLES - SELECT; COMPRAS.RECEPCIONES_COMPRA - SELECT/UPDATE; COMPRAS.RECEPCIONES_COMPRA_DETALLES - SELECT/UPDATE; INVENTARIO.ACTIVOS - SELECT; INVENTARIO.ACTIVOS_CONTENIDOS - SELECT; INVENTARIO.ACTIVOS_EVENTOS - INSERT/SELECT; INVENTARIO.LOTES - SELECT; INVENTARIO.LOTES_EXISTENCIAS - SELECT; INVENTARIO.MOVIMIENTOS_DETALLES - SELECT; INVENTARIO.MOVIMIENTOS_DETALLES_ACTIVOS - INSERT; INVENTARIO.MOVIMIENTOS_DETALLES_LOTES - INSERT/SELECT.
Auditoría: Registra información mediante objetos del esquema AUDITORIA referenciados por el procedimiento.
Parámetros de entrada: Empresa, recepción, motivo y versión del documento.
Parámetros de sesión: Sesión y usuario responsables de la reversión.
Parámetros de salida: Código funcional, mensaje y filas afectadas.
Transacción: Movimiento de salida, stock, lotes, activos, recepción y orden se confirman juntos.
