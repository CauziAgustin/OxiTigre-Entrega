Tablas utilizadas: INVENTARIO.DEPOSITOS - SELECT; INVENTARIO.EXISTENCIAS - SELECT; INVENTARIO.MOVIMIENTOS - INSERT; INVENTARIO.MOVIMIENTOS_DETALLES - INSERT; INVENTARIO.PRODUCTOS - SELECT; INVENTARIO.RESERVAS_STOCK - SELECT; INVENTARIO.UBICACIONES - SELECT.
