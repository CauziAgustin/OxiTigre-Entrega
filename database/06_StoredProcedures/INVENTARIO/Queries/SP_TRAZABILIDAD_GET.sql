Tablas utilizadas: COMERCIAL.CLIENTES - SELECT; CONFIGURACION.SUCURSALES - SELECT; CONFIGURACION.UNIDADES_MEDIDA - SELECT; INVENTARIO.ACTIVOS - SELECT; INVENTARIO.ACTIVOS_CONTENIDOS - SELECT; INVENTARIO.ACTIVOS_EVENTOS - SELECT; INVENTARIO.DEPOSITOS - SELECT; INVENTARIO.INCIDENTES - SELECT; INVENTARIO.LOTES - SELECT; INVENTARIO.LOTES_EXISTENCIAS - SELECT; INVENTARIO.MANTENIMIENTOS - SELECT; INVENTARIO.MEDICIONES_ACTIVOS - SELECT; INVENTARIO.PRESTAMOS - SELECT; INVENTARIO.PRESTAMOS_DETALLES - SELECT; INVENTARIO.PRODUCTOS - SELECT; INVENTARIO.TRANSFORMACIONES - SELECT; INVENTARIO.TRANSFORMACIONES_DETALLES - SELECT; INVENTARIO.UBICACIONES - SELECT.
